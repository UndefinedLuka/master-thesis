"""Produce the serialization context-window fit LaTeX table."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from visualizations.config import (
    CONTEXT_WINDOW_TOKENS,
    DATASET_LABELS,
    DATASET_ORDER,
    FORMAT_LABELS,
    LATEX_ROW_END,
    SERIALIZATION_FIT_TABLE_FILENAME,
    SERIALIZATION_FIT_TABLE_LABEL,
    SERIALIZATION_FORMAT_ORDER,
    TOKENIZER_FAMILY_LABELS,
    TOKENIZER_FAMILY_ORDER,
)
from visualizations.serialization_data import present_order, require_columns, sort_summary


def calculate_database_fit(
    report: pd.DataFrame,
    *,
    context_window_tokens: int = CONTEXT_WINDOW_TOKENS,
) -> pd.DataFrame:
    """Count database payloads at or below the context-window token limit."""
    if context_window_tokens <= 0:
        raise ValueError("Context-window size must be positive")
    require_columns(
        report,
        ("dataset", "database_id", "format", "tokenizer_family", "tokenizer_label", "tokens"),
    )
    data = report.copy()
    data["fits_context"] = data["tokens"].le(context_window_tokens)
    summary = (
        data.groupby(
            ["dataset", "format", "tokenizer_family", "tokenizer_label"],
            as_index=False,
            observed=True,
        )
        .agg(
            fitting_databases=("fits_context", "sum"),
            total_databases=("database_id", "nunique"),
        )
        .reset_index(drop=True)
    )
    summary["fitting_databases"] = summary["fitting_databases"].astype(int)
    summary["total_databases"] = summary["total_databases"].astype(int)
    summary["fit_percentage"] = (
        summary["fitting_databases"] / summary["total_databases"] * 100.0
    )
    return sort_summary(summary, family_column="tokenizer_family")


def render_database_fit_table(
    summary: pd.DataFrame,
    *,
    context_window_tokens: int = CONTEXT_WINDOW_TOKENS,
    coverage_validated: bool,
    caption: str | None = None,
    label: str = SERIALIZATION_FIT_TABLE_LABEL,
) -> str:
    """Render fitting-database counts by dataset, format, and tokenizer family."""
    require_columns(
        summary,
        (
            "dataset",
            "format",
            "tokenizer_family",
            "fitting_databases",
            "total_databases",
            "fit_percentage",
        ),
    )
    if summary.empty:
        raise ValueError("No database-fit counts are available to render")
    if caption is None:
        caption = (
            f"Serialized database payloads fitting within {context_window_tokens:,} tokens. "
            "Cells report the number of fitting databases, the total number of databases, "
            "and the percentage."
        )

    families = present_order(TOKENIZER_FAMILY_ORDER, summary["tokenizer_family"])
    rows: list[str] = []
    datasets = present_order(DATASET_ORDER, summary["dataset"])
    for dataset in datasets:
        dataset_rows = summary[summary["dataset"].eq(dataset)]
        formats = present_order(SERIALIZATION_FORMAT_ORDER, dataset_rows["format"])
        for index, serialization_format in enumerate(formats):
            format_rows = dataset_rows[dataset_rows["format"].eq(serialization_format)]
            cells = [
                DATASET_LABELS.get(dataset, dataset) if index == 0 else "",
                FORMAT_LABELS.get(serialization_format, serialization_format),
            ]
            for family in families:
                family_rows = format_rows[format_rows["tokenizer_family"].eq(family)]
                if family_rows.empty:
                    cells.append("--")
                    continue
                row = family_rows.iloc[0]
                cells.append(
                    f"{int(row['fitting_databases'])}/{int(row['total_databases'])} "
                    f"({float(row['fit_percentage']):.1f}\\%)"
                )
            rows.append("    " + " & ".join(cells) + LATEX_ROW_END)
        if dataset != datasets[-1]:
            rows.append(r"    \midrule")

    validation_note = (
        "The complete set of 31 databases, six formats, and three tokenizer families was "
        "validated."
        if coverage_validated
        else "Coverage validation was skipped."
    )
    note = (
        "Counts apply only to the serialized database payload. Instructions, questions, "
        "chat-template tokens, and output-token headroom are excluded. "
        + validation_note
    )
    family_headers = [TOKENIZER_FAMILY_LABELS.get(family, family) for family in families]
    return "\n".join(
        [
            "% Generated by visualizations.serialization_database_fit; "
            "do not edit values manually.",
            r"\begin{table}[htbp]",
            r"  \centering",
            f"  \\caption{{{caption}}}",
            f"  \\label{{{label}}}",
            f"  \\begin{{tabular}}{{@{{}}ll{'c' * len(families)}@{{}}}}",
            r"    \toprule",
            "    Dataset & Format & " + " & ".join(family_headers) + LATEX_ROW_END,
            r"    \midrule",
            *rows,
            r"    \bottomrule",
            r"  \end{tabular}",
            r"  \vspace{0.4em}",
            f"  \\parbox{{\\linewidth}}{{\\scriptsize \\textit{{Note:}} {note}}}",
            r"\end{table}",
            "",
        ]
    )


def generate_database_fit_table(
    report: pd.DataFrame,
    output_dir: Path,
    *,
    context_window_tokens: int = CONTEXT_WINDOW_TOKENS,
    coverage_validated: bool,
) -> Path:
    """Calculate and write the context-fit table, returning its path."""
    output_path = output_dir / SERIALIZATION_FIT_TABLE_FILENAME
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        render_database_fit_table(
            calculate_database_fit(report, context_window_tokens=context_window_tokens),
            context_window_tokens=context_window_tokens,
            coverage_validated=coverage_validated,
        ),
        encoding="utf-8",
    )
    return output_path

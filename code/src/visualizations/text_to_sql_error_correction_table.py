"""Produce the Text-to-SQL error-correction outcome table."""

from __future__ import annotations

from pathlib import Path

from visualizations.config import (
    DATASET_LABELS,
    DATASET_ORDER,
    LATEX_ROW_END,
    RETRY_OUTCOME_LABELS,
    RETRY_OUTCOME_ORDER,
    TEXT_TO_SQL_RETRY_TABLE_FILENAME,
    TEXT_TO_SQL_RETRY_TABLE_LABEL,
)
from visualizations.text_to_sql_retry_data import TextToSqlRetryAnalysis


def render_error_correction_table(
    analysis: TextToSqlRetryAnalysis,
    *,
    label: str = TEXT_TO_SQL_RETRY_TABLE_LABEL,
) -> str:
    """Render terminal execution attempt and retry-time counts."""
    rows: list[str] = []
    for dataset in DATASET_ORDER:
        dataset_rows = analysis.outcome_summary[
            analysis.outcome_summary["dataset"].eq(dataset)
        ].set_index("terminal_outcome")
        for index, outcome in enumerate(RETRY_OUTCOME_ORDER):
            row = dataset_rows.loc[outcome]
            rows.append(
                "    "
                + " & ".join(
                    (
                        DATASET_LABELS[dataset] if index == 0 else "",
                        RETRY_OUTCOME_LABELS[outcome],
                        f"{int(row['run_count']):,}",
                        f"{float(row['run_percentage']):.2f}\\%",
                        f"{float(row['total_retry_generation_s']):,.1f}",
                        f"{float(row['average_retry_generation_s']):.2f}",
                    )
                )
                + LATEX_ROW_END
            )
        if dataset != DATASET_ORDER[-1]:
            rows.append(r"    \midrule")

    return "\n".join(
        [
            "% Generated by visualizations.text_to_sql_error_correction_table; "
            "do not edit values manually.",
            r"\begin{table}[htbp]",
            r"  \centering",
            r"  \small",
            (
                r"  \caption{Text-to-SQL terminal execution outcome and retry-generation "
                r"overhead.}"
            ),
            f"  \\label{{{label}}}",
            r"  \resizebox{\textwidth}{!}{%",
            r"  \begin{tabular}{@{}llrrrr@{}}",
            r"    \toprule",
            (
                r"    Dataset & Terminal outcome & Runs & Share & Added time (s) & "
                r"Mean added (s) \\"
            ),
            r"    \midrule",
            *rows,
            r"    \bottomrule",
            r"  \end{tabular}%",
            r"  }",
            r"  \vspace{0.4em}",
            (
                r"  \parbox{\linewidth}{\scriptsize \textit{Note:} Attempt labels identify "
                r"the generation on which SQL first executed successfully. Added time is "
                r"model-generation time from "
                r"attempts after the first; per-attempt SQL execution time was not persisted "
                r"separately and is excluded.}"
            ),
            r"\end{table}",
            "",
        ]
    )


def generate_error_correction_table(
    analysis: TextToSqlRetryAnalysis,
    output_dir: Path,
) -> Path:
    """Write the Text-to-SQL error-correction table and return its path."""
    output_path = output_dir / TEXT_TO_SQL_RETRY_TABLE_FILENAME
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_error_correction_table(analysis), encoding="utf-8")
    return output_path

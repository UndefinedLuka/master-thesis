"""Produce the absolute operational measurements on the cross-pipeline common cohort."""

from __future__ import annotations

from pathlib import Path

from visualizations.common_cohort_data import CommonCohortAnalysis
from visualizations.config import (
    COMMON_COHORT_METHOD_LABELS,
    COMMON_COHORT_TABLE_FILENAME,
    COMMON_COHORT_TABLE_LABEL,
    DATASET_LABELS,
    DATASET_ORDER,
    LATEX_ROW_END,
)
from visualizations.latex_numbers import num


def render_common_cohort_table(analysis: CommonCohortAnalysis) -> str:
    """Render per-run means without pooling the six direct serialization alternatives."""
    rows: list[str] = []
    datasets = [value for value in DATASET_ORDER if value in analysis.question_counts]
    for dataset in datasets:
        panel = analysis.summary[analysis.summary["dataset"].eq(dataset)]
        for index, row in enumerate(panel.itertuples(index=False)):
            rows.append(
                "    "
                + " & ".join(
                    (
                        DATASET_LABELS[dataset] if index == 0 else "",
                        COMMON_COHORT_METHOD_LABELS[row.method],
                        num(row.average_input_tokens, 0),
                        num(row.average_output_tokens, 1),
                        num(row.average_ttft_s, 3),
                        num(row.average_generation_time_s, 3),
                        num(row.average_sql_execution_time_s, 3),
                        num(row.average_total_latency_s, 3),
                    )
                )
                + LATEX_ROW_END
            )
        if dataset != datasets[-1]:
            rows.append(r"    \midrule")
    return "\n".join(
        [
            "% Generated by visualizations.common_cohort_operational_table; do not edit values.",
            r"\begin{table}[htbp]",
            r"  \centering",
            r"  \small",
            r"  \caption{Mean operational measurements for both pipelines on the same "
            r"recorded context-fit questions and models.}",
            f"  \\label{{{COMMON_COHORT_TABLE_LABEL}}}",
            r"  \setlength{\tabcolsep}{4pt}",
            r"  \resizebox{\textwidth}{!}{%",
            r"  \begin{tabular}{@{}llrrrrrr@{}}",
            r"    \toprule",
            r"    Dataset & Method & Input tokens & Output tokens & TTFT (s) & "
            r"Generation (s) & SQL (s) & Total (s) \\",
            r"    \midrule",
            *rows,
            r"    \bottomrule",
            r"  \end{tabular}%",
            r"  }",
            r"\end{table}",
            "",
        ]
    )


def generate_common_cohort_table(analysis: CommonCohortAnalysis, output_dir: Path) -> Path:
    """Write one table for the matched comparison."""
    path = output_dir / COMMON_COHORT_TABLE_FILENAME
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_common_cohort_table(analysis), encoding="utf-8")
    return path

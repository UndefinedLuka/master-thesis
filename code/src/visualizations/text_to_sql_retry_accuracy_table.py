"""Produce cumulative recovery counts and retrieval accuracy among recovered SQL runs."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from visualizations.config import (
    DATASET_LABELS,
    DATASET_ORDER,
    LATEX_ROW_END,
    TEXT_TO_SQL_RETRY_ACCURACY_TABLE_FILENAME,
    TEXT_TO_SQL_RETRY_ACCURACY_TABLE_LABEL,
)
from visualizations.latex_numbers import num
from visualizations.text_to_sql_retry_data import TextToSqlRetryAnalysis
from visualizations.uncertainty import table_estimate


def render_retry_accuracy_table(
    analysis: TextToSqlRetryAnalysis,
    *,
    label: str = TEXT_TO_SQL_RETRY_ACCURACY_TABLE_LABEL,
) -> str:
    """Show recovery/failure counts and recovered-only scores with bootstrap intervals."""
    rows: list[str] = []
    for dataset in DATASET_ORDER:
        selected = analysis.accuracy_summary.loc[
            analysis.accuracy_summary["dataset"].eq(dataset)
            & analysis.accuracy_summary["retry_budget"].gt(0)
        ].sort_values("retry_budget")
        if selected.empty:
            continue
        if rows:
            rows.append(r"    \midrule")
        count = int(selected.iloc[0]["run_count"])
        rows.append(
            r"    \multicolumn{7}{@{}l}{\textit{"
            + DATASET_LABELS[dataset] + " (" + num(count) + " runs entering correction)}}"
            + LATEX_ROW_END
        )
        for _, row in selected.iterrows():
            cells = [
                str(row["retry_label"]), num(int(row["newly_executed_run_count"])),
                num(int(row["cumulative_executed_run_count"])),
                num(int(row["unrecovered_run_count"])),
            ]
            for metric, decimals, scale, suffix in (
                ("normalized_exact_match", 3, 1, ""),
                ("rouge_l_f", 3, 1, ""),
                ("bertscore_f", 3, 1, ""),
            ):
                cells.append(
                    "---" if pd.isna(row[metric]) else table_estimate(
                        row, metric, decimals, scale=scale, suffix=suffix,
                    )
                )
            rows.append("    " + " & ".join(cells) + LATEX_ROW_END)
    return "\n".join([
        "% Generated by visualizations.text_to_sql_retry_accuracy_table; "
        "do not edit values manually.",
        r"\begin{table}[htbp]",
        r"  \centering",
        r"  \small",
        r"  \caption{Cumulative recovery and retrieval accuracy for runs entering correction "
        r"in the answerable cohort. Newly executable counts refer to each retry; recovered "
        r"and still failed counts are cumulative. Mean scores include only runs recovered "
        r"by that point; runs still failing are excluded rather than assigned zero scores.}",
        f"  \\label{{{label}}}",
        r"  \resizebox{\textwidth}{!}{%",
        r"  \begin{tabular}{@{}lrrrrrr@{}}",
        r"    \toprule",
        "    Retry budget & Newly executable & Recovered & Still failed & NEM & ROUGE-L & BERTScore"
        + LATEX_ROW_END,
        r"    \midrule",
        *rows,
        r"    \bottomrule",
        r"  \end{tabular}%",
        r"  }",
        r"\end{table}",
        "",
    ])


def generate_retry_accuracy_table(
    analysis: TextToSqlRetryAnalysis, output_dir: Path,
) -> Path:
    """Write the cumulative SQL retry-accuracy table and return its path."""
    path = output_dir / TEXT_TO_SQL_RETRY_ACCURACY_TABLE_FILENAME
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_retry_accuracy_table(analysis), encoding="utf-8")
    return path

"""Produce the mean serialization-token LaTeX table."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from visualizations.config import (
    DATASET_LABELS,
    DATASET_ORDER,
    FORMAT_LABELS,
    LATEX_ROW_END,
    SERIALIZATION_AVERAGE_TABLE_FILENAME,
    SERIALIZATION_AVERAGE_TABLE_LABEL,
    SERIALIZATION_FORMAT_ORDER,
)
from visualizations.serialization_data import present_order, require_columns, sort_summary


def calculate_average_tokens(report: pd.DataFrame) -> pd.DataFrame:
    """Calculate mean payload tokens and the within-dataset ratio to the lowest mean."""
    require_columns(report, ("dataset", "database_id", "format", "tokenizer_family", "tokens"))
    summary = (
        report.groupby(["dataset", "format"], as_index=False, observed=True)
        .agg(
            mean_tokens=("tokens", "mean"),
            database_count=("database_id", "nunique"),
            tokenizer_family_count=("tokenizer_family", "nunique"),
            observation_count=("tokens", "size"),
        )
        .reset_index(drop=True)
    )
    if summary.empty:
        return summary.assign(relative_to_lowest=pd.Series(dtype=float))
    minimum = summary.groupby("dataset", observed=True)["mean_tokens"].transform("min")
    summary["relative_to_lowest"] = summary["mean_tokens"] / minimum
    return sort_summary(summary)


def render_average_tokens_table(
    summary: pd.DataFrame,
    *,
    coverage_validated: bool,
    caption: str = (
        "Mean token count of serialized database payloads. Relative token use is normalized "
        "within each dataset to the format with the lowest mean."
    ),
    label: str = SERIALIZATION_AVERAGE_TABLE_LABEL,
) -> str:
    """Render the mean-token and relative-efficiency LaTeX table."""
    require_columns(summary, ("dataset", "format", "mean_tokens", "relative_to_lowest"))
    if summary.empty:
        raise ValueError("No average token counts are available to render")

    rows: list[str] = []
    datasets = present_order(DATASET_ORDER, summary["dataset"])
    for dataset in datasets:
        dataset_rows = summary[summary["dataset"].eq(dataset)]
        formats = present_order(SERIALIZATION_FORMAT_ORDER, dataset_rows["format"])
        for index, serialization_format in enumerate(formats):
            row = dataset_rows[dataset_rows["format"].eq(serialization_format)].iloc[0]
            dataset_label = DATASET_LABELS.get(dataset, dataset) if index == 0 else ""
            rows.append(
                "    "
                + " & ".join(
                    (
                        dataset_label,
                        FORMAT_LABELS.get(serialization_format, serialization_format),
                        f"{float(row['mean_tokens']):,.0f}",
                        f"{float(row['relative_to_lowest']):.2f}$\\times$",
                    )
                )
                + LATEX_ROW_END
            )
        if dataset != datasets[-1]:
            rows.append(r"    \midrule")

    validation_note = (
        "The complete set of 31 databases, six formats, and three tokenizer families was "
        "validated."
        if coverage_validated
        else "Coverage validation was skipped."
    )
    note = (
        "Means are arithmetic averages across all databases in the named dataset and all three "
        "representative tokenizer families. Only the serialized database payload is counted; "
        "instructions, questions, chat-template tokens, and output-token headroom are excluded. "
        + validation_note
    )
    return "\n".join(
        [
            "% Generated by visualizations.serialization_average_tokens; "
            "do not edit values manually.",
            r"\begin{table}[htbp]",
            r"  \centering",
            f"  \\caption{{{caption}}}",
            f"  \\label{{{label}}}",
            r"  \begin{tabular}{@{}llrr@{}}",
            r"    \toprule",
            r"    Dataset & Format & Mean tokens & Relative to lowest" + LATEX_ROW_END,
            r"    \midrule",
            *rows,
            r"    \bottomrule",
            r"  \end{tabular}",
            r"  \vspace{0.4em}",
            f"  \\parbox{{\\linewidth}}{{\\scriptsize \\textit{{Note:}} {note}}}",
            r"\end{table}",
            "",
        ]
    )


def generate_average_tokens_table(
    report: pd.DataFrame,
    output_dir: Path,
    *,
    coverage_validated: bool,
) -> Path:
    """Calculate and write the mean-token table, returning its path."""
    output_path = output_dir / SERIALIZATION_AVERAGE_TABLE_FILENAME
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        render_average_tokens_table(
            calculate_average_tokens(report),
            coverage_validated=coverage_validated,
        ),
        encoding="utf-8",
    )
    return output_path

"""Produce the Text-to-SQL retrieval-accuracy summary table."""

from __future__ import annotations

from pathlib import Path

from visualizations.config import (
    DATASET_LABELS,
    LATEX_ROW_END,
    TEXT_TO_SQL_RETRIEVAL_TABLE_FILENAME,
    TEXT_TO_SQL_RETRIEVAL_TABLE_LABEL,
)
from visualizations.text_to_sql_data import TextToSqlAnalysis


def render_text_to_sql_retrieval_table(
    analysis: TextToSqlAnalysis,
    *,
    label: str = TEXT_TO_SQL_RETRIEVAL_TABLE_LABEL,
) -> str:
    """Render dataset-level Text-to-SQL accuracy and execution outcomes."""
    rows: list[str] = []
    for row in analysis.dataset_summary.itertuples(index=False):
        rows.append(
            "    "
            + " & ".join(
                (
                    DATASET_LABELS.get(row.dataset, row.dataset),
                    f"{row.normalized_exact_match:.3f}",
                    f"{row.bertscore_f:.3f}",
                    f"{row.rouge_l_f:.3f}",
                    f"{row.execution_success_rate * 100:.1f}\\%",
                    f"{row.result_match_rate * 100:.1f}\\%",
                )
            )
            + LATEX_ROW_END
        )
    return "\n".join(
        [
            "% Generated by visualizations.text_to_sql_retrieval_accuracy_table; "
            "do not edit values manually.",
            r"\begin{table}[htbp]",
            r"  \centering",
            (
                r"  \caption{Mean Text-to-SQL retrieval scores and query-execution outcomes "
                r"by dataset.}"
            ),
            f"  \\label{{{label}}}",
            r"  \begin{tabular}{@{}lrrrrr@{}}",
            r"    \toprule",
            (
                r"    Dataset & NEM & BERTScore F1 & ROUGE-L F1 & Executed & "
                r"Correct result \\"
            ),
            r"    \midrule",
            *rows,
            r"    \bottomrule",
            r"  \end{tabular}",
            r"  \vspace{0.4em}",
            (
                r"  \parbox{\linewidth}{\scriptsize \textit{Note:} Text-similarity means "
                r"include zero-scored failed SQL runs. Executed is the share of generated "
                r"queries that ran successfully within the retry limit; Correct result is the "
                r"share returning the reference rows.}"
            ),
            r"\end{table}",
            "",
        ]
    )


def generate_text_to_sql_retrieval_table(
    analysis: TextToSqlAnalysis,
    output_dir: Path,
) -> Path:
    """Write the Text-to-SQL retrieval table and return its path."""
    output_path = output_dir / TEXT_TO_SQL_RETRIEVAL_TABLE_FILENAME
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_text_to_sql_retrieval_table(analysis), encoding="utf-8")
    return output_path

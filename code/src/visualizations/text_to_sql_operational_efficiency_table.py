"""Produce the Text-to-SQL operational-efficiency summary table."""

from __future__ import annotations

from pathlib import Path

from visualizations.config import (
    DATASET_LABELS,
    LATEX_ROW_END,
    TEXT_TO_SQL_OPERATIONAL_TABLE_FILENAME,
    TEXT_TO_SQL_OPERATIONAL_TABLE_LABEL,
)
from visualizations.text_to_sql_data import TextToSqlAnalysis
from visualizations.uncertainty import table_estimate


def render_text_to_sql_operational_table(
    analysis: TextToSqlAnalysis,
    *,
    label: str = TEXT_TO_SQL_OPERATIONAL_TABLE_LABEL,
) -> str:
    """Render dataset-level Text-to-SQL token, retry, and latency means."""
    rows: list[str] = []
    for row in analysis.dataset_summary.itertuples(index=False):
        rows.append(
            "    "
            + " & ".join(
                (
                    DATASET_LABELS.get(row.dataset, row.dataset),
                    table_estimate(row, "average_input_tokens", 0),
                    table_estimate(row, "average_output_tokens", 1),
                    table_estimate(row, "average_cumulative_ttft_s"),
                    table_estimate(row, "average_generation_time_s"),
                    table_estimate(row, "average_sql_execution_time_s", 3),
                    table_estimate(row, "average_total_latency_s"),
                    table_estimate(row, "average_retries"),
                )
            )
            + LATEX_ROW_END
        )
    return "\n".join(
        [
            "% Generated by visualizations.text_to_sql_operational_efficiency_table; "
            "do not edit values manually.",
            r"\begin{table}[htbp]",
            r"  \centering",
            r"  \small",
            r"  \caption{Mean Text-to-SQL operational-efficiency measurements by dataset "
            r"on the answerable cohort.}",
            f"  \\label{{{label}}}",
            r"  \resizebox{\textwidth}{!}{%",
            r"  \begin{tabular}{@{}lrrrrrrr@{}}",
            r"    \toprule",
            (
                r"    Dataset & Input tokens & Output tokens & TTFT (s) & Generation (s) & "
                r"SQL (s) & Total (s) & Retries \\"
            ),
            r"    \midrule",
            *rows,
            r"    \bottomrule",
            r"  \end{tabular}%",
            r"  }",
            r"  \vspace{0.4em}",
            (
                r"  \parbox{\linewidth}{\scriptsize \textit{Note:} Token counts and model "
                r"times are accumulated across the initial generation and all correction "
                r"attempts, including terminal failures. TTFT is the sum of first-token waits "
                r"across attempts; Generation "
                r"is the remaining model time. Total also includes SQL execution. Brackets "
                r"show pointwise \qty{95}{\percent} database-bootstrap confidence intervals.}"
            ),
            r"\end{table}",
            "",
        ]
    )


def generate_text_to_sql_operational_table(
    analysis: TextToSqlAnalysis,
    output_dir: Path,
) -> Path:
    """Write the Text-to-SQL operational table and return its path."""
    output_path = output_dir / TEXT_TO_SQL_OPERATIONAL_TABLE_FILENAME
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_text_to_sql_operational_table(analysis), encoding="utf-8")
    return output_path

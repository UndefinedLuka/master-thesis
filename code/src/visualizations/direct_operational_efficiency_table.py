"""Produce the direct-context operational-efficiency LaTeX table."""

from __future__ import annotations

from pathlib import Path

from visualizations.config import (
    DATASET_LABELS,
    DATASET_ORDER,
    DIRECT_OPERATIONAL_TABLE_FILENAME,
    DIRECT_OPERATIONAL_TABLE_LABEL,
    FORMAT_LABELS,
    LATEX_ROW_END,
    SERIALIZATION_FORMAT_ORDER,
)
from visualizations.direct_efficiency_data import DirectEfficiencyAnalysis
from visualizations.latex_numbers import num, percent
from visualizations.uncertainty import table_estimate


def render_direct_operational_table(
    analysis: DirectEfficiencyAnalysis,
    *,
    caption: str = (
        "Mean operational-efficiency measurements for Direct Context Inference on the common "
        "complete-case cohort."
    ),
    label: str = DIRECT_OPERATIONAL_TABLE_LABEL,
) -> str:
    """Render average token and latency measurements by dataset and format."""
    summary = analysis.summary
    required = {
        "dataset",
        "format",
        "average_input_tokens",
        "average_output_tokens",
        "average_ttft_s",
        "average_generation_time_s",
        "average_total_latency_s",
    }
    missing = required.difference(summary.columns)
    if missing:
        raise ValueError(f"Operational summary is missing: {', '.join(sorted(missing))}")
    if summary.empty:
        raise ValueError("No direct operational measurements are available to render")

    rows: list[str] = []
    datasets = [value for value in DATASET_ORDER if value in set(summary["dataset"])]
    for dataset in datasets:
        dataset_rows = summary[summary["dataset"].eq(dataset)]
        formats = [
            value for value in SERIALIZATION_FORMAT_ORDER if value in set(dataset_rows["format"])
        ]
        for index, serialization_format in enumerate(formats):
            row = dataset_rows[dataset_rows["format"].eq(serialization_format)].iloc[0]
            rows.append(
                "    "
                + " & ".join(
                    (
                        DATASET_LABELS.get(dataset, dataset) if index == 0 else "",
                        FORMAT_LABELS.get(serialization_format, serialization_format),
                        table_estimate(row, "average_input_tokens", 0),
                        table_estimate(row, "average_output_tokens", 1),
                        table_estimate(row, "average_ttft_s"),
                        table_estimate(row, "average_generation_time_s"),
                        table_estimate(row, "average_total_latency_s"),
                    )
                )
                + LATEX_ROW_END
            )
        if dataset != datasets[-1]:
            rows.append(r"    \midrule")

    cohort_parts = [
        f"{DATASET_LABELS.get(dataset, dataset)}: "
        f"{num(analysis.question_counts[dataset])} questions across "
        f"{num(analysis.database_counts[dataset])} databases"
        for dataset in datasets
    ]
    note = (
        "The matched cohort includes "
        + "; ".join(cohort_parts)
        + f", with all {num(analysis.model_count)} retained models and all displayed formats. "
        "Generation time is measured from the first output token to completion; total latency "
        "is measured from request submission to completion. Brackets show pointwise "
        f"{percent(95)} database-bootstrap confidence intervals. BIRD intervals describe only "
        "the two observed databases."
    )
    return "\n".join(
        [
            "% Generated by visualizations.direct_operational_efficiency_table; "
            "do not edit values manually.",
            r"\begin{table}[htbp]",
            r"  \centering",
            r"  \small",
            f"  \\caption{{{caption}}}",
            f"  \\label{{{label}}}",
            r"  \setlength{\tabcolsep}{4pt}",
            r"  \resizebox{\textwidth}{!}{%",
            r"  \begin{tabular}{@{}llrrrrr@{}}",
            r"    \toprule",
            (
                r"    Dataset & Format & Input tokens & Output tokens & TTFT (s) & "
                r"Generation (s) & Total latency (s) \\"
            ),
            r"    \midrule",
            *rows,
            r"    \bottomrule",
            r"  \end{tabular}%",
            r"  }",
            r"  \vspace{0.4em}",
            f"  \\parbox{{\\linewidth}}{{\\scriptsize \\textit{{Note:}} {note}}}",
            r"\end{table}",
            "",
        ]
    )


def generate_direct_operational_table(
    analysis: DirectEfficiencyAnalysis,
    output_dir: Path,
) -> Path:
    """Write the direct operational-efficiency table and return its path."""
    output_path = output_dir / DIRECT_OPERATIONAL_TABLE_FILENAME
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_direct_operational_table(analysis), encoding="utf-8")
    return output_path
